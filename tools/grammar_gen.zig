//! Grammar tables: `.spgrammar` files → one Zig source file of compiled
//! `grammar.Grammar` values, in the order the files are named.
//!
//!     grammar-gen <out.zig> <a.spgrammar> <b.spgrammar> ...
//!
//! `zig build` runs it on every file of `grammars/` and compiles the result
//! in as the `registry` module, so the binary starts with its tables made:
//! it neither interprets the grammar compiler at compile time nor runs it at
//! start-up. A mistake in a file is `file:line: message` on standard error
//! and exit status 1, which stops the build.
//!
//! Contents:
//! - `pub fn main(init: std.process.Init) !void`

const std = @import("std");
const grammar = @import("grammar");
const Writer = std.Io.Writer;
const assert = std.debug.assert;

const grammar_bytes_max = 16 << 20;

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const argv = try init.minimal.args.toSlice(arena);
    if (argv.len < 3) fail(io, "usage: grammar-gen <out.zig> <file.spgrammar>...\n", .{});

    var text: Writer.Allocating = .init(arena);
    const out = &text.writer;
    try out.writeAll("//! Generated by tools/grammar_gen.zig from grammars/*.spgrammar. Not edited by hand.\n");
    try out.writeAll("const grammar = @import(\"grammar\");\n\n");
    try out.print("pub const grammars = [{d}]grammar.Grammar{{\n", .{argv.len - 2});
    for (argv[2..]) |path| {
        const src = try std.Io.Dir.cwd().readFileAlloc(io, path, arena, .limited(grammar_bytes_max));
        var diag: grammar.Diag = .{};
        const compiled = grammar.compile(arena, src, "", &diag) catch |e| switch (e) {
            error.OutOfMemory => return e,
            error.BadGrammar => fail(io, "{s}\n", .{diag.msg}),
        };
        try literal(out, compiled);
        try out.writeAll(",\n");
    }
    try out.writeAll("};\n");
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = argv[1], .data = text.written() });
}

// ---- private ----

fn fail(io: std.Io, comptime fmt: []const u8, args: anytype) noreturn {
    var buf: [4096]u8 = undefined;
    var stderr = std.Io.File.stderr().writer(io, &buf);
    stderr.interface.print(fmt, args) catch {};
    stderr.interface.flush() catch {};
    std.process.exit(1);
}

/// `value` as a Zig expression that evaluates to it wherever its type is
/// known: structs as `.{ .field = ... }`, slices as `&.{ ... }`, text as a
/// string. Covers the types a compiled grammar is made of, and refuses to
/// compile for any other.
fn literal(out: *Writer, value: anytype) Writer.Error!void {
    const T = @TypeOf(value);
    switch (@typeInfo(T)) {
        .bool, .int => try out.print("{}", .{value}),
        .@"enum" => try out.print(".{f}", .{std.zig.fmtId(@tagName(value))}),
        .optional => if (value) |inner| try literal(out, inner) else try out.writeAll("null"),
        .array => try items(out, ".{", &value),
        .pointer => |pointer| {
            comptime assert(pointer.size == .slice);
            if (pointer.child == u8) return out.print("\"{f}\"", .{std.zig.fmtString(value)});
            try items(out, "&.{", value);
        },
        .@"struct" => |info| {
            try out.writeAll(".{");
            inline for (info.field_names) |name| {
                try out.print(" .{f} = ", .{std.zig.fmtId(name)});
                try literal(out, @field(value, name));
                try out.writeByte(',');
            }
            try out.writeAll(" }");
        },
        .@"union" => switch (value) {
            inline else => |payload, tag| {
                try out.print(".{{ .{f} = ", .{std.zig.fmtId(@tagName(tag))});
                try literal(out, payload);
                try out.writeAll(" }");
            },
        },
        else => @compileError("grammar_gen: no literal form for " ++ @typeName(T)),
    }
}

fn items(out: *Writer, open: []const u8, list: anytype) Writer.Error!void {
    try out.writeAll(open);
    for (list) |item| {
        try out.writeByte(' ');
        try literal(out, item);
        try out.writeByte(',');
    }
    try out.writeAll(" }");
}
