const std = @import("std");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    // Every grammars/*.spgrammar file becomes a dialect. There is no list to
    // keep in sync: drop a file in the directory and rebuild.
    const io = b.graph.io;
    b.dependOnDirectoryContents(b.path("grammars"));
    var dir = b.root.openDir(io, "grammars", .{ .iterate = true }) catch @panic("grammars/ directory not found");
    defer dir.close(io);
    var names: std.ArrayList([]const u8) = .empty;
    var it = dir.iterate();
    while (it.next(io) catch @panic("cannot list grammars/")) |entry| {
        if (entry.kind != .file or !std.mem.endsWith(u8, entry.name, ".spgrammar")) continue;
        names.append(b.allocator, b.dupe(entry.name)) catch @panic("OOM");
    }
    std.mem.sort([]const u8, names.items, {}, struct {
        fn lessThan(_: void, x: []const u8, y: []const u8) bool {
            return std.mem.lessThan(u8, x, y);
        }
    }.lessThan);

    var reg: std.ArrayList(u8) = .empty;
    reg.appendSlice(b.allocator, "//! Generated by build.zig from grammars/*.spgrammar.\npub const sources = .{\n") catch @panic("OOM");
    for (names.items) |n| reg.print(b.allocator, "    @embedFile(\"{s}\"),\n", .{n}) catch @panic("OOM");
    reg.appendSlice(b.allocator, "};\n") catch @panic("OOM");
    const generated = b.addWriteFiles();
    const registry = b.createModule(.{ .root_source_file = generated.add("registry.zig", reg.items) });
    for (names.items) |n| {
        registry.addAnonymousImport(n, .{ .root_source_file = b.path(b.fmt("grammars/{s}", .{n})) });
    }

    const sprack = b.addModule("sprack", .{
        .root_source_file = b.path("src/root.zig"),
        .target = target,
        .optimize = optimize,
    });
    sprack.addImport("registry", registry);

    const exe = b.addExecutable(.{
        .name = "sprack",
        .root_module = b.createModule(.{
            .root_source_file = b.path("src/main.zig"),
            .target = target,
            .optimize = optimize,
            .imports = &.{.{ .name = "sprack", .module = sprack }},
        }),
    });
    b.installArtifact(exe);

    // C ABI for the Python package and any other host language.
    const lib = b.addLibrary(.{
        .name = "sprack",
        .linkage = .dynamic,
        .root_module = b.createModule(.{
            .root_source_file = b.path("src/capi.zig"),
            .target = target,
            .optimize = optimize,
            .imports = &.{.{ .name = "sprack", .module = sprack }},
        }),
    });
    b.installArtifact(lib);

    // The CPython extension module, `zig build py`. It is built against
    // the limited C API and resolves the interpreter's symbols when loaded,
    // so no Python headers or libraries are needed to build it.
    const pyext = b.addLibrary(.{
        .name = "_core",
        .linkage = .dynamic,
        .root_module = b.createModule(.{
            .root_source_file = b.path("src/pyext.zig"),
            // Zig's own TLS is not set up in a dlopen'd library; glibc's is.
            .link_libc = true,
            .target = target,
            .optimize = optimize,
            .imports = &.{.{ .name = "sprack", .module = sprack }},
        }),
    });
    pyext.linker_allow_shlib_undefined = true;
    const ext_name = if (target.result.os.tag == .windows) "_core.pyd" else "_core.abi3.so";
    const install_py = b.addInstallFileWithDir(pyext.getEmittedBin(), .{ .custom = "../python/sprack" }, ext_name);
    b.step("py", "Build the Python extension into python/sprack/").dependOn(&install_py.step);

    const run = b.addRunArtifact(exe);
    run.step.dependOn(b.getInstallStep());
    run.addPassthruArgs();
    b.step("run", "Run the sprack command line tool").dependOn(&run.step);

    const tests = b.addTest(.{ .root_module = sprack });
    const test_step = b.step("test", "Run all tests");
    test_step.dependOn(&b.addRunArtifact(tests).step);
    test_step.dependOn(&b.addRunArtifact(b.addTest(.{ .root_module = lib.root_module })).step);
}
